  function overviewReportData(scope, assessmentId) {
    var asm = N.ASSESSMENTS.filter(function (a) { return a.id === assessmentId; })[0];
    var label, students;
    if (scope.type === "school") { label = "Whole School"; students = N.Store.state.students.slice(); }
    else if (scope.type === "grade") {
      label = "" + N.gradeLabel(scope.grade);
      students = N.Store.state.students.filter(function (s) { return s.grade === scope.grade; });
    } else if (scope.type === "class") {
      var selectedClass = N.Store.classOf(scope.classId);
      if (!selectedClass) throw new Error("Choose a valid class or stream for the performance report.");
      label = classLabel(selectedClass.grade, selectedClass.stream);
      students = N.Store.state.students.filter(function (s) { return s.classId === selectedClass.id; });
    } else if (scope.type === "classes") {
      label = "All Classes and Streams";
      students = N.Store.state.students.slice();
    } else {
      throw new Error("Choose a valid performance report scope.");
    }
    var seen = {}, subjects = [];
    students.forEach(function (st) { N.studentSubjects(st).forEach(function (s) { if (!seen[s.id]) { seen[s.id] = 1; subjects.push(s); } }); });
    var rows = subjects.map(function (s) {
      var relevant = students.filter(function (st) { return N.studentSubjects(st).some(function (x) { return x.id === s.id; }); });
      return { subject: s, share: N.subjectShare(assessmentId, s.id, relevant) };
    });
    var applicableClasses = N.Store.state.classes.filter(function (c) {
      if (scope.type === "grade") return c.grade === scope.grade;
      if (scope.type === "class") return c.id === scope.classId;
      return scope.type === "classes" || scope.type === "school";
    }).sort(function (a, b) { return a.grade - b.grade || String(a.stream || "").localeCompare(String(b.stream || "")); });
    var classSummaries = [];
    var groupedByGrade = {};
    applicableClasses.forEach(function (c) {
      (groupedByGrade[c.grade] || (groupedByGrade[c.grade] = [])).push(c);
    });
    Object.keys(groupedByGrade).sort(function (a, b) { return Number(a) - Number(b); }).forEach(function (grade) {
      var gradeStudents = students.filter(function (st) { return st.grade === Number(grade); });
      if (scope.type !== "class") {
        classSummaries.push({
          label: N.gradeLabel(Number(grade)) + " total",
          kind: "grade",
          summary: performanceSummary(gradeStudents, assessmentId),
        });
      }
      groupedByGrade[grade].forEach(function (c) {
        var classStudents = students.filter(function (st) { return st.classId === c.id; });
        classSummaries.push({
          label: classLabel(c.grade, c.stream),
          kind: "class",
          summary: performanceSummary(classStudents, assessmentId),
        });
      });
    });
    return {
      label: label,
      assessment: asm,
      rows: rows,
      studentCount: students.length,
      summary: performanceSummary(students, assessmentId),
      classSummaries: classSummaries,
    };
  }
