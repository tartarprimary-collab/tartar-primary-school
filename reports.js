  function shareOrDownload(doc, filename, title, text) {
    var file;
    try { file = doc.file(filename); } catch (e) { file = null; }
    if (file && global.navigator && navigator.canShare && navigator.canShare({ files: [file] })) {
      navigator.share({ files: [file], title: title, text: text }).catch(function () {});
    } else if (global.navigator && navigator.share) {
      navigator.share({ title: title, text: text }).catch(function () {});
    } else {
      doc.save(filename);
      var waUrl = "https://wa.me/?text=" + encodeURIComponent(text + " (PDF downloaded \u2014 attach it from your downloads to share on WhatsApp.)");
      global.open(waUrl, "_blank");
    }
  }
  // Print = open the same generated PDF in a new tab, so the browser's own
