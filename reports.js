  function learnerReportData(studentId, assessmentId) {
    var st = N.Store.student(studentId);
    var asm = N.ASSESSMENTS.filter(function (a) { return a.id === assessmentId; })[0];
    var subs = N.studentSubjects(st);
    var rows = subs.map(function (s) {
      var mark = N.Store.scoreOf(assessmentId, st.id, s.id);
      var code = mark == null ? null : N.bandCode(mark);
      return { subject: s.name, mark: mark, code: code, remark: mark == null ? "Not yet assessed this term." : N.bandRemark(code, s.name) };
    });
    var marks = rows.map(function (r) { return r.mark; }).filter(function (m) { return m != null; });
    var counts = N.bandCounts(marks);
    var competencies = N.CORE_COMPETENCIES.map(function (name) { return { name: name, code: null }; });
    var attendanceRecorded = N.TERM3_DAYS.some(function (day) { return !!N.Store.attendanceOn(day, st.id); });
    var att = attendanceRecorded ? N.attendancePct(st) : null;
    var ledger = N.Store.ledgerOf(st.id);
    return {
      student: st, assessment: asm, rows: rows, counts: counts, marksEntered: marks.length, subjectsTotal: subs.length,
      competencies: competencies, attendancePct: att, ledger: ledger, groupLabel: N.groupLabel(st.grade),
      teacherComment: teacherComment(), principalComment: principalComment(),
    };
  }
