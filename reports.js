  function classReportData(grade, group, assessmentId) {
    var asm = N.ASSESSMENTS.filter(function (a) { return a.id === assessmentId; })[0];
    var students = N.Store.state.students.filter(function (s) { return s.grade === grade && s.stream === group; })
      .slice().sort(function (a, b) { return a.name.localeCompare(b.name); });
    var subjects = N.subjectsFor(grade, group);
    var rows = students.map(function (st) { return { student: st, marks: subjects.map(function (s) { return N.Store.scoreOf(assessmentId, st.id, s.id); }) }; });
    var subjectStats = subjects.map(function (s) { return N.subjectShare(assessmentId, s.id, students); });
    return {
      grade: grade, group: group, classLabel: classLabel(grade, group), assessment: asm, subjects: subjects, rows: rows,
      subjectStats: subjectStats, summary: performanceSummary(students, assessmentId), groupLabel: N.groupLabel(grade),
    };
  }
  function classReportHtml(d) {
    var head = "<tr><th>Adm</th><th>Name</th>" + d.subjects.map(function (s) { return '<th style="text-align:center">' + s.id.toUpperCase() + "</th>"; }).join("") + "</tr>";
    var body = d.rows.map(function (r) {
      return '<tr><td class="mono small">' + N.esc(r.student.adm) + "</td><td>" + N.esc(r.student.name) + "</td>" +
        r.marks.map(function (mk) { return '<td style="text-align:center">' + Shell.scoreLevel(mk) + "</td>"; }).join("") + "</tr>";
    }).join("");
    var footAvg = '<tr class="rt-foot"><td colspan="2">Class average (internal)</td>' + d.subjectStats.map(function (s) { return '<td style="text-align:center" class="tabular">' + (s.avg == null ? "&mdash;" : s.avg.toFixed(0)) + "</td>"; }).join("") + "</tr>";
    var footMeet = '<tr class="rt-foot"><td colspan="2">Meeting expectation +</td>' + d.subjectStats.map(function (s) { return '<td style="text-align:center" class="tabular">' + N.pct(s.meetingPlus) + "</td>"; }).join("") + "</tr>";
    return '<div class="report-doc">' + reportHeadBlock("Class Assessment\nSheet").replace("\n", "<br>") +
      '<div class="report-grid">' + kv("Class", d.classLabel) + kv("Assessment", d.assessment.label) + kv("Learners", d.rows.length + " on the roll") + kv("Term", N.SCHOOL.termLabel) + "</div>" +
      '<h3 class="rp-h3">Class / stream overall performance</h3>' + summaryHtml(d.summary) +
      '<div class="report-scroll"><table class="report-table"><thead>' + head + "</thead><tbody>" + body + footAvg + footMeet + "</tbody></table></div>" +
      '<p class="small muted mt-3">Subject codes: ' + d.subjects.map(function (s) { return s.id.toUpperCase() + " = " + s.name; }).join(" &middot; ") + "</p>" + methodNote() + footerBlock() + "</div>";
  }
