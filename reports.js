  function performanceSummary(students, assessmentId) {
    var marks = [], possible = 0, assessed = {};
    students.forEach(function (st) {
      var studentMarks = N.studentAssessmentMarks(st, assessmentId);
      possible += studentMarks.length;
      studentMarks.forEach(function (mark) {
        if (mark == null) return;
        marks.push(mark);
        assessed[st.id] = true;
      });
    });
    return {
      learners: students.length,
      learnersAssessed: Object.keys(assessed).length,
      entries: marks.length,
      possibleEntries: possible,
      coverage: possible ? marks.length / possible : 0,
      average: N.averageMark(marks),
      counts: N.bandCounts(marks),
    };
  }
  function summaryHtml(summary) {
    var distribution = summary.entries
      ? ["EE", "ME", "AE", "BE"].map(function (band) {
        return kv(band, summary.counts[band] + " (" + N.pct(summary.counts[band] / summary.entries) + ")");
      }).join("")
      : kv("Achievement bands", "No marks recorded");
    return '<div class="report-grid">' +
      kv("Learners with marks", summary.learnersAssessed + " of " + summary.learners) +
      kv("Marks entered", summary.entries + " of " + summary.possibleEntries + " (" + N.pct(summary.coverage) + ")") +
      kv("Mean numeric score (internal)", summary.average == null ? "Not available" : summary.average.toFixed(1) + " / 100") +
      distribution + "</div>";
  }
  function summaryPdf(doc, y, summary) {
    doc.text(doc.margin, y, "Overall performance", { size: 10.5, bold: true, color: PDFDoc.COLORS.primary });
    y -= 13;
    var detail = summary.entries
      ? "Learners with marks: " + summary.learnersAssessed + " of " + summary.learners +
        " | Marks entered: " + summary.entries + " of " + summary.possibleEntries +
        " (" + N.pct(summary.coverage) + ") | Mean numeric score (internal): " + summary.average.toFixed(1) + "/100"
      : "No marks are recorded for this assessment.";
    y = doc.block(doc.margin, y, detail, doc.pageW - 2 * doc.margin, { size: 8.2, color: PDFDoc.COLORS.soft, lineHeight: 10 });
    if (summary.entries) {
      var levels = ["EE", "ME", "AE", "BE"].map(function (band) {
        return band + ": " + summary.counts[band] + " (" + N.pct(summary.counts[band] / summary.entries) + ")";
      }).join("   ");
      y = doc.block(doc.margin, y - 1, "Achievement bands: " + levels, doc.pageW - 2 * doc.margin, { size: 8.2, color: PDFDoc.COLORS.soft, lineHeight: 10 });
    }
    return y - 8;
  }

