  function openPdfTab(doc) {
    try {
      var url = URL.createObjectURL(doc.blob());
      global.open(url, "_blank");
      setTimeout(function () { URL.revokeObjectURL(url); }, 60000);
    } catch (e) {
      global.open(doc.dataUri(), "_blank");
    }
  }


